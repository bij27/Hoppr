#!/usr/bin/env node
// The Hoppr frog: one shape, generated here, used everywhere.
//
//   node scripts/brand/generate.mjs
//
// Writes src/components/frog-paths.ts (used by the in-app frog and loading animation) and renders
// the app icon, Android adaptive icon layers, splash images and favicon with headless Chrome
// (set CHROME=/path/to/chrome if it isn't in the default Windows/macOS location).

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

// Brand colors (match src/constants/theme.ts).
const GREEN = '#2E9E5B';
const GREEN_DARK_MODE = '#4CC27A';
const PAPER = '#FAF8F5';
const INK = '#0E0E0E';

const f = (n) => Math.round(n * 10) / 10;

/** Convex hull of two circles: a limb segment tapering from radius r1 to r2. */
function seg([x1, y1, r1], [x2, y2, r2]) {
  const th = Math.atan2(y2 - y1, x2 - x1);
  const d = Math.hypot(x2 - x1, y2 - y1);
  const ph = Math.acos((r1 - r2) / d);
  const p = (x, y, r, a) => `${f(x + r * Math.cos(a))} ${f(y + r * Math.sin(a))}`;
  return (
    `M${p(x1, y1, r1, th + ph)}L${p(x2, y2, r2, th + ph)}` +
    `A${r2} ${r2} 0 ${2 * ph > Math.PI ? 1 : 0} 0 ${p(x2, y2, r2, th - ph)}` +
    `L${p(x1, y1, r1, th - ph)}A${r1} ${r1} 0 ${ph < Math.PI / 2 ? 1 : 0} 0 ${p(x1, y1, r1, th + ph)}Z`
  );
}
const circle = (x, y, r) => `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0Z`;
const chain = (pts) => pts.slice(1).map((p, i) => seg(pts[i], p)).join('');
const toes = (base, tips) => tips.map((t) => seg(base, t) + circle(t[0], t[1], t[2] + 5)).join('');

// Facing right, mid-leap, body angled up. Coordinates are in a 1000-unit drawing space.
const body =
  'M330 600C300 520 420 400 590 340C690 305 780 290 840 320C880 340 882 380 850 405' +
  'C810 437 740 450 690 470C600 505 520 580 450 620C400 645 350 640 330 600Z';
// Eye bump with a highlight cut out (draw with fill-rule evenodd).
const eye = circle(742, 300, 40) + circle(752, 291, 12);
const backLeg =
  chain([[400, 590, 62], [235, 680, 38], [120, 760, 22], [60, 815, 13]]) +
  toes([60, 815, 11], [[5, 830, 8], [20, 868, 8], [55, 880, 8]]);
const farBackLeg =
  chain([[380, 560, 46], [250, 600, 30], [150, 640, 18], [95, 668, 11]]) +
  toes([95, 668, 9], [[40, 660, 7], [45, 695, 7]]);
const frontLeg =
  chain([[660, 470, 30], [745, 545, 20], [830, 575, 13]]) +
  toes([830, 575, 10], [[880, 555, 7], [888, 588, 7], [865, 615, 7]]);
const farFrontLeg =
  chain([[700, 445, 22], [790, 470, 15], [860, 470, 10]]) +
  toes([860, 470, 8], [[905, 452, 6], [908, 480, 6]]);

const SOLID = [farBackLeg, farFrontLeg, backLeg, body, frontLeg];
// The frog spans about x -5…915, y 245…888; this square frames it with a little room.
const VIEWBOX = '-20 90 960 960';

// ---------------------------------------------------------------------------------------------
// 1. Shape data for the app
// ---------------------------------------------------------------------------------------------
writeFileSync(
  join(ROOT, 'src', 'components', 'frog-paths.ts'),
  `// Generated by scripts/brand/generate.mjs. Don't edit by hand; change the generator and re-run it.

/** Square viewBox that frames the leaping frog. */
export const FROG_VIEWBOX = '${VIEWBOX}';

/** Body and legs (fill-rule nonzero). */
export const FROG_SOLID_PATHS = ${JSON.stringify(SOLID, null, 2)};

/** Eye bump with its highlight cut out (fill-rule evenodd). */
export const FROG_EYE_PATH = ${JSON.stringify(eye)};
`,
);
console.log('✓ src/components/frog-paths.ts');

// ---------------------------------------------------------------------------------------------
// 2. Images
// ---------------------------------------------------------------------------------------------
/** SVG of the frog filling `fill` (0–1) of a square, centered, on `bg` (or transparent). */
function svg({ size, fg, bg, fill }) {
  const side = 960 / fill;
  const x = -20 + 480 - side / 2;
  const y = 90 + 480 - side / 2;
  const paths = SOLID.map((d) => `<path d="${d}"/>`).join('') + `<path fill-rule="evenodd" d="${eye}"/>`;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${f(x)} ${f(y)} ${f(side)} ${f(side)}">` +
    (bg ? `<rect x="${f(x)}" y="${f(y)}" width="${f(side)}" height="${f(side)}" fill="${bg}"/>` : '') +
    `<g fill="${fg}">${paths}</g></svg>`
  );
}

const IMAGES = [
  // iOS/default icon: full square, no transparency.
  { file: 'icon.png', size: 1024, fg: GREEN, bg: PAPER, fill: 0.78 },
  // Android adaptive icon: background is a flat color in app.json; keep the frog inside the safe zone.
  { file: 'android-icon-foreground.png', size: 1024, fg: GREEN, fill: 0.56 },
  { file: 'android-icon-monochrome.png', size: 1024, fg: '#000000', fill: 0.56 },
  // Splash: transparent, sized by imageWidth in app.json.
  { file: 'splash-icon.png', size: 1024, fg: GREEN, fill: 1 },
  { file: 'splash-icon-dark.png', size: 1024, fg: GREEN_DARK_MODE, fill: 1 },
  { file: 'favicon.png', size: 64, fg: GREEN, fill: 1 },
];

const chrome =
  process.env.CHROME ??
  [
    'C:/Program Files/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  ].find(existsSync);

if (!chrome) {
  console.log('Chrome not found (set CHROME=...); skipped rendering images.');
  process.exit(0);
}

const tmp = mkdtempSync(join(tmpdir(), 'hoppr-brand-'));
for (const img of IMAGES) {
  const html = join(tmp, `${img.file}.html`);
  writeFileSync(html, `<html><body style="margin:0;background:transparent">${svg(img)}</body></html>`);
  const out = join(ROOT, 'assets', 'images', img.file);
  execFileSync(chrome, [
    '--headless=new',
    '--disable-gpu',
    '--hide-scrollbars',
    '--default-background-color=00000000',
    `--window-size=${img.size},${img.size}`,
    `--screenshot=${out}`,
    `file:///${html.replace(/\\/g, '/')}`,
  ], { stdio: 'ignore' });
  console.log(`✓ assets/images/${img.file}`);
}

export { INK, PAPER };
